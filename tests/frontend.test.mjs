import assert from 'node:assert/strict';
import { buildEoCsv, parseEoCsv, normalizeRegistrationNumber } from '../src/utils.js';
assert.equal(normalizeRegistrationNumber('52'),'052');
assert.equal(normalizeRegistrationNumber('001'),'001');
const tickets=Array.from({length:65},(_,i)=>({registrationNumber:String(i+1).padStart(3,'0'),checkToken:`2027${String(i+1).padStart(3,'0')}`}));
const empty=buildEoCsv(tickets);
assert.ok(empty.includes('052,2027052,FALSE'));
assert.throws(()=>parseEoCsv(empty),/8 TRUE/);
let rows=empty.split('\r\n');
for(let i=1;i<=8;i++)rows[i]=rows[i].replace(/FALSE$/,'TRUE');
const valid=rows.join('\r\n');
const results=parseEoCsv(valid);
assert.equal(results.length,65);
assert.equal(results.filter(r=>r.selected).length,8);
assert.equal(results[0].registrationNumber,'001');
assert.throws(()=>parseEoCsv(valid.replace('2027001','2027999')),/token harus/);
assert.throws(()=>parseEoCsv(valid.replace('002,2027002','001,2027001')),/duplikat/);
assert.throws(()=>parseEoCsv(valid.replace('TRUE','YEAH')),/TRUE atau FALSE/);
assert.throws(()=>parseEoCsv(valid.replace('008,2027008,TRUE\r\n','')),/65 data/);
console.log('PASS frontend: CSV template, preserving 001, EO 8 TRUE, reject wrong token, duplicate, invalid truth and incomplete set.');
